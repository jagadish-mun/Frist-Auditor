"""Task 13: why is the score–success correlation weak on the no-flow tasks? Analysis only.

    python tools/diagnose.py      # reads runs/agents/results_traj.json, the defect catalogs, docs/*_results.json

Three candidate explanations, each measured:
  (a) ceiling / range restriction — how often agents succeed anyway, how little success varies;
  (b) irrelevance — how many clones have a planted defect on the path of each task at all;
  (c) the score misses what matters — among clones whose defects ARE on a task's path, does the score separate
      the clones where the agent fails from those where it succeeds?
"On the path" uses the ground-truth defect catalogs, not the auditor:
  page level:    a defect's pages ("*" = all) intersect the pages the task visits on the real site;
  element level: page level AND one of the defect's `expect` keywords equals (or is contained in) the name of an
                 element the task clicks or the label of a field it fills/selects, on the real site.
The draft clone has no catalog defects; its one functional difference (hand review) is on fare_rules only.
Writes runs/diagnose/{RESULTS.md,results.json}.
"""
import json
import statistics as st
import sys
from pathlib import Path

from scipy.stats import mannwhitneyu, spearmanr

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools")); sys.path.insert(0, str(ROOT / "refapp"))
from agents import TASKS  # noqa: E402
from defects import DEFECTS, REBUILT_DEFECTS, TIERS  # noqa: E402
from heldout_defects import HELDOUT_DEFECTS  # noqa: E402

CAT = {**DEFECTS, **REBUILT_DEFECTS, **HELDOUT_DEFECTS}
AGENTS = ("replay", "semantic")


def clone_defects(name):
    if name in TIERS:
        return list(TIERS[name])
    if name == "drift_rebuild":
        return ["subtle_drift"]
    if name == "rebuilt_all4":
        return list(REBUILT_DEFECTS)
    for pre in ("single_", "tpl_", "rebuilt_"):
        if name.startswith(pre) and name[len(pre):] in CAT:
            return [name[len(pre):]]
    return []          # rebuilt, draft


def norm(s):
    return " ".join((s or "").lower().split())


def on_path(defect, task_ref):
    pages = set(task_ref["semantic_pages"])
    names = {norm(s.get("name") or s.get("label")) for s in task_ref["traj"]}
    d = CAT[defect]
    page = "*" in d["pages"] or bool(pages & set(d["pages"]))
    kws = [norm(kw) for _, _, kw in d["expect"] if kw]
    elem = any(kw == n or kw in n for kw in kws for n in names if n)
    return page, page and elem


def main():
    agents = {a["clone"]: a for a in json.loads((ROOT / "runs/agents/results_traj.json").read_text())}
    scores = {}
    for f in ("docs/validation_results.json", "docs/heldout_results.json", "docs/draft_results.json"):
        r = json.loads((ROOT / f).read_text())
        for sc in r["_meta"]["scorings"]:
            for k, v in r[sc].items():
                scores.setdefault(sc, {}).setdefault(k, v["overall"])
    ref = agents["real"]["tasks"]
    clones = [c for c in agents if c != "real" and not c.startswith("sweep_") and c in scores["v3"]]
    nonflow = [t for t, s in TASKS.items() if s["overlap"] == "none"]
    succ = lambda c, t, ag: agents[c]["tasks"][t][ag]
    rate = lambda c, ag, cs=None: sum(succ(c, t, ag) for t in nonflow) / len(nonflow)
    out = {"n_clones": len(clones), "tasks": nonflow}
    L = ["# Correlation diagnosis (Task 13) — data", "",
         f"Generated by `python tools/diagnose.py`. {len(clones)} non-nested clones × {len(nonflow)} no-flow tasks "
         f"({', '.join(nonflow)}). Agent outcomes: runs/agents/results_traj.json. Scores: docs/*_results.json.", ""]

    # (a) ceiling
    L += ["## (a) Ceiling and range", "", "| Agent | pairs | success share | clones at 100% no-flow success | "
          "variance of no-flow success across clones | distinct success values | variance of v3 score |",
          "|---|---|---|---|---|---|---|"]
    for ag in AGENTS:
        pairs = [succ(c, t, ag) for c in clones for t in nonflow]
        per = [rate(c, ag) for c in clones]
        out[f"a|{ag}"] = {"share": sum(pairs) / len(pairs), "at_ceiling": sum(p == 1 for p in per), "var": st.pvariance(per),
                          "distinct": sorted(set(round(p, 3) for p in per))}
        L.append(f"| {ag} | {len(pairs)} | {sum(pairs) / len(pairs):.3f} | {sum(p == 1 for p in per)}/{len(clones)} | "
                 f"{st.pvariance(per):.4f} | {len(set(per))} | {st.pvariance([scores['v3'][c] for c in clones]):.4f} |")

    # (b) relevance
    L += ["", "## (b) Are the defects on the tasks' paths at all?", "",
          "| Task | replay success share | semantic success share | clones with a defect on the page path | … on the element path |",
          "|---|---|---|---|---|"]
    paths = {}
    for t in nonflow:
        pg = [c for c in clones if any(on_path(d, ref[t])[0] for d in clone_defects(c))]
        el = [c for c in clones if any(on_path(d, ref[t])[1] for d in clone_defects(c))]
        paths[t] = {"page": pg, "element": el}
        out[f"b|{t}"] = {"page": len(pg), "element": el}
        L.append(f"| {t} | {sum(succ(c, t, 'replay') for c in clones) / len(clones):.2f} | "
                 f"{sum(succ(c, t, 'semantic') for c in clones) / len(clones):.2f} | {len(pg)}/{len(clones)} | {len(el)}/{len(clones)} |")
    any_el = [c for c in clones if any(c in paths[t]["element"] for t in nonflow)]
    pairs_el = [(c, t) for c in clones for t in nonflow if c in paths[t]["element"]]
    pairs_pg = [(c, t) for c in clones for t in nonflow if c in paths[t]["page"]]
    out["b"] = {"clones_any_element": len(any_el), "pairs_element": len(pairs_el), "pairs_page": len(pairs_pg),
                "pairs_total": len(clones) * len(nonflow)}
    L += ["", f"Clones with a defect on the element path of at least one no-flow task: **{len(any_el)}/{len(clones)}**. "
          f"(clone, task) pairs with a defect on the element path: **{len(pairs_el)}/{len(clones) * len(nonflow)}**; "
          f"on the page path: {len(pairs_pg)}.", ""]

    L += ["### Where do the failures come from?", "",
          "| Agent | failures | on element path | page path only | no planted defect on path | on-path pairs where the agent still succeeds |",
          "|---|---|---|---|---|---|"]
    for ag in AGENTS:
        fails = [(c, t) for c in clones for t in nonflow if not succ(c, t, ag)]
        el = [x for x in fails if x[0] in paths[x[1]]["element"]]
        pg = [x for x in fails if x[0] in paths[x[1]]["page"] and x not in el]
        rest = [x for x in fails if x not in el and x not in pg]
        ok_el = [x for x in pairs_el if succ(x[0], x[1], ag)]
        out[f"fail|{ag}"] = {"n": len(fails), "element": len(el), "page_only": [f"{c}/{t}" for c, t in pg],
                             "none": [f"{c}/{t}" for c, t in rest], "onpath_success": len(ok_el)}
        L.append(f"| {ag} | {len(fails)} | {len(el)} | {len(pg)}: {', '.join(f'{c}/{t}' for c, t in pg) or '—'} | "
                 f"{len(rest)}: {', '.join(f'{c}/{t}' for c, t in rest) or '—'} | {len(ok_el)}/{len(pairs_el)} |")

    # (c) does the score separate fail/success where it could?
    L += ["", "## (c) Does the score separate failing from succeeding clones?", "",
          "Mann–Whitney U, one-sided (clones in failing (clone, task) pairs score lower than in succeeding pairs).", "",
          "| Agent | Scoring | ρ, all clones | ρ, clones with an on-path defect (n) | median score, failing pairs | "
          "median score, succeeding pairs | U-test p |", "|---|---|---|---|---|---|---|"]
    for ag in AGENTS:
        for sc in ("v3", "v2", "v1"):
            r_all = spearmanr([scores[sc][c] for c in clones], [rate(c, ag) for c in clones]).correlation
            r_sub = spearmanr([scores[sc][c] for c in any_el], [rate(c, ag) for c in any_el]).correlation
            fs = [scores[sc][c] for c in clones for t in nonflow if not succ(c, t, ag)]
            ss = [scores[sc][c] for c in clones for t in nonflow if succ(c, t, ag)]
            p = mannwhitneyu(fs, ss, alternative="less").pvalue if fs else float("nan")
            out[f"c|{ag}|{sc}"] = {"rho_all": r_all, "rho_onpath": r_sub, "n_onpath": len(any_el),
                                   "med_fail": st.median(fs) if fs else None, "med_succ": st.median(ss), "p": p}
            L.append(f"| {ag} | {sc} | {r_all:+.2f} | {r_sub:+.2f} ({len(any_el)}) | {st.median(fs) if fs else float('nan'):.3f} | "
                     f"{st.median(ss):.3f} | {p:.2g} |")
    o = ROOT / "runs" / "diagnose"; o.mkdir(parents=True, exist_ok=True)
    (o / "RESULTS.md").write_text("\n".join(L) + "\n"); (o / "results.json").write_text(json.dumps(out, indent=1, default=str))
    print("\n".join(L))


if __name__ == "__main__":
    main()
