"""Correlate clone fidelity scores with proxy-agent success on the real site (SPEC §9.3).

    python tools/correlate.py      # reads runs/agents/results.json + runs/validation*/results.json

Scores come from the main, held-out (--heldout) and draft (--draft) validation runs. Statistics use only
non-nested clones (the cumulative-sweep clones are excluded). Writes runs/agents/{RESULTS.md,correlation.png,stats.json}.
"""
import json
import sys
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "tools"))
from agents import TASKS  # noqa: E402
from tools.plot import chart  # noqa: E402

OUT = ROOT / "runs" / "agents"
AGENTS = ("replay", "semantic")
B, SEED = 2000, 0


def load_scores():
    """{scoring: {clone_name: overall}} merged from every validation run that exists."""
    scores = {}
    for d in ("validation", "validation_heldout", "validation_draft"):
        f = ROOT / "runs" / d / "results.json"
        if not f.exists():
            continue
        res = json.loads(f.read_text())
        for sc in res["_meta"]["scorings"]:
            for name, r in res[sc].items():
                scores.setdefault(sc, {}).setdefault(name, r["overall"])   # main run wins for shared names (noise, rebuilt)
    for sc in scores:
        scores[sc]["real"] = scores[sc]["noise_1"]
    return scores


def success(a, ag, tasks):
    return sum(a["tasks"][t][ag] for t in tasks) / len(tasks)


def rho_ci(x, y, rng, idx):
    r = spearmanr(x, y).correlation
    bs = [spearmanr(x[i], y[i]).correlation for i in idx]
    return r, np.nanpercentile(bs, 2.5), np.nanpercentile(bs, 97.5), np.array(bs)


def main():
    agents = json.loads((OUT / "results.json").read_text())
    scores = load_scores()
    scorings = [s for s in ("v3", "v2", "v1") if s in scores]
    rows = [a for a in agents if all(a["clone"] in scores[s] for s in scorings)]
    missing = [a["clone"] for a in agents if a not in rows]
    alltasks = list(TASKS)
    nonflow = [t for t, s in TASKS.items() if s["overlap"] == "none"]
    flat = [a for a in rows if not a["clone"].startswith("sweep_") and a["clone"] != "real"]
    analyses = {
        "(a) all 14 tasks, non-nested clones": (flat, alltasks),
        f"(b) {len(nonflow)} no-flow-overlap tasks, non-nested clones": (flat, nonflow),
        "(c) all tasks, held-out clones only": ([a for a in flat if "_ho_" in a["clone"]], alltasks),
        "(c') no-flow-overlap tasks, held-out clones only": ([a for a in flat if "_ho_" in a["clone"]], nonflow),
    }
    rng = np.random.default_rng(SEED)
    L = ["# Agent correlation (SPEC §9.3), Phase 2: proxy agents, 14 tasks", "",
         "Generated by `python tools/agents.py --workers 3 && python tools/correlate.py`. Scores from `python validate.py "
         "--scoring v3,v2,v1`, `--heldout` and `--draft`. Success = share of tasks completed on the REAL site after "
         f"training on the clone. Bootstrap: {B} resamples of clones, seed {SEED}, 95% percentile intervals.", "",
         f"No-flow-overlap tasks: {', '.join(nonflow)}.", ""]
    if missing:
        L += [f"Clones without scores (excluded): {', '.join(missing)}.", ""]
    stats = {}
    for title, (sub, tasks) in analyses.items():
        L += [f"## {title} — n = {len(sub)}", "",
              "| Agent | " + " | ".join(f"{s} ρ [95% CI]" for s in scorings) + " | ρ(v3) − ρ(v2) [CI] | ρ(v3) − ρ(v1) [CI] |",
              "|---|" + "---|" * (len(scorings) + 2)]
        idx = [rng.integers(0, len(sub), len(sub)) for _ in range(B)]
        for ag in AGENTS:
            y = np.array([success(a, ag, tasks) for a in sub])
            cells, bs = [], {}
            for s in scorings:
                x = np.array([scores[s][a["clone"]] for a in sub])
                r, lo, hi, bs[s] = rho_ci(x, y, rng, idx)
                stats[f"{title}|{ag}|{s}"] = [float(r), float(lo), float(hi)]
                cells.append(f"{r:+.2f} [{lo:+.2f}, {hi:+.2f}]")
            for other in ("v2", "v1"):
                d = bs["v3"] - bs[other]
                cells.append(f"[{np.nanpercentile(d, 2.5):+.2f}, {np.nanpercentile(d, 97.5):+.2f}]")
            L.append(f"| {ag} | " + " | ".join(cells) + " |")
        L.append("")
    L += ["## Per-clone results", "", "| Clone | " + " | ".join(scorings) + " | replay (14) | semantic (14) | replay (no-flow) | semantic (no-flow) |",
          "|---|" + "---|" * (len(scorings) + 4)]
    for a in rows:
        L.append(f"| {a['clone']} | " + " | ".join(f"{scores[s][a['clone']]:.3f}" for s in scorings) + " | "
                 + " | ".join(f"{success(a, ag, t):.2f}" for t in (alltasks, nonflow) for ag in AGENTS) + " |")
    panels = [{"title": f"Scoring {s}: fidelity vs real-site success, 14 tasks (n={len(flat)})",
               "xlabel": f"fidelity score ({s})", "ylabel": "real-site task success",
               "xr": (min(0.3, min(scores[s][a['clone']] for a in flat)), 1.0), "yr": (0.0, 1.05),
               "series": [(f"{ag} ρ={stats[f'(a) all 14 tasks, non-nested clones|{ag}|{s}'][0]:+.2f}",
                           [(scores[s][a["clone"]], success(a, ag, alltasks) - 0.012 * k) for a in flat])
                          for k, ag in enumerate(AGENTS)]} for s in scorings]
    chart(OUT / "correlation.png", panels)
    L += ["", "![correlation](correlation.png)", "", "Squares (semantic) drawn 0.012 lower than circles (replay) so overlaps stay visible.", ""]
    (OUT / "RESULTS.md").write_text("\n".join(L) + "\n")
    (OUT / "stats.json").write_text(json.dumps(stats, indent=2))
    print("\n".join(L[:60]))


if __name__ == "__main__":
    main()
